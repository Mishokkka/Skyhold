export function createUiReviewDraft() {
  return {
    decisions: { ...Object.fromEntries(UI_AUDIT_PROPOSALS.map(({ id }) => {
      const note = id === "audit-type" ? "Светлый цвет заголовков на тёмном фоне."
        : id === "audit-density" ? "Тесные отступы 3 × 5 px: на пару пикселей плотнее образца." : "";
      return [id, { choice: note ? "custom" : "agree", note }];
    })), ...Object.fromEntries(UI_BEHAVIOR_PROPOSALS.map(({ id }) => [id, { choice: "agree",
      note: id === "behavior-save" ? "Режим и статус в правом верхнем углу заголовка, без отдельной строки" : "" }])),
      ...Object.fromEntries(UI_ROW_CARD_PROPOSALS.map(({ id }) => [id, {
        choice: id.startsWith("cards-") ? "keep" : "agree",
        note: id === "rows-chips" ? "Все выпадающие списки: читаемый текст на контрастном фоне, включая раскрытые варианты."
          : id === "cards-header" ? "Прежний вариант лучше использует пространство и линии." : ""
      }])), ...Object.fromEntries(UI_BUILDING_EDITOR_PROPOSALS.map(({ id }) => [id, { choice: "agree",
        note: id === "editor-construction" ? "Стадии, действия и требования развития в одной компактной строке; иконки требований в цветах отраслей"
          : id === "editor-projects" ? "Участники выбираются из списка жителей"
          : id === "editor-income" ? "Категории выбираются из списка каталога"
          : id === "editor-housing" ? "Места при достаточной ширине располагаются в нескольких колонках" : "" }])) },
    generalNote: ""
  };
}

export function countUiReviewDecisions(draft = {}) {
  return UI_BUILDING_EDITOR_PROPOSALS.filter(({ id }) => CHOICE_LABELS[draft?.decisions?.[id]?.choice]).length;
}

export function formatUiReviewSummary(draft = {}) {
  const lines = ["FBL Skyhold — вкладки редактора здания", "Карточки зданий: прежний вид сохранён. Прежние решения сохраняются.", "Выбор в окне ничего не применяет.", ""];
  for (const proposal of UI_BUILDING_EDITOR_PROPOSALS) {
    const decision = draft?.decisions?.[proposal.id] ?? {};
    const label = CHOICE_LABELS[decision.choice] ?? "Не решено";
    const note = String(decision.note ?? "").trim().replace(/\s+/g, " ");
    lines.push(`${proposal.title}: ${label}${note ? ` — ${note}` : decision.choice === "custom" ? " — требуется описание" : ""}.`);
  }
  const generalNote = String(draft?.generalNote ?? "").trim().replace(/\s+/g, " ");
  if (generalNote) lines.push("", `Общий комментарий: ${generalNote}`);
  return lines.join("\n");
}
