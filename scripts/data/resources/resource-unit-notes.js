export function resourceUnitNote(id, { foodEdible = false, category = "" } = {}) {
  let meaning = UNIT_NOTES[id];
  if (!meaning && foodEdible) meaning = "Одна учётная порция готовой еды для рациона жителя. Количество упаковок и физическая масса зависят от блюда.";
  if (!meaning && id.startsWith("alcohol-")) meaning = "Мерная товарная ёмкость напитка заданного вида, качества и крепости. Слабый и крепкий напитки имеют разные выходы при перегонке.";
  if (!meaning && id.startsWith("armament-")) meaning = "Полный комплект вооружения и снаряжения для отряда из пяти человек.";
  if (!meaning) meaning = category === "Кристаллы" ? "Один кристалл либо мерная упаковка кристаллического материала соответствующей категории." : "Одна товарная упаковка или партия указанного материала по местному стандарту.";
  return `Смысл 1 ЕД.: ${meaning} Масса и объём служат пояснением; склад и перевозки используют прежние ЕД. и грузовые очки.`;
}
