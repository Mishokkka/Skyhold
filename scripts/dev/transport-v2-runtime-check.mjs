import assert from "node:assert/strict";
import { planTransportChain } from "../engines/transport/planner.js";
import { bookTransportOrder, cancelTransportOrder, advanceTransportOrders, resolveTransportIncident } from "../engines/transport/runtime.js";
import { reservedResourceBatchQuantities } from "../core/resource-batches.js";

const cargo = [{ lotId: "grain", rowId: "r1", batchId: "b1", resourceId: "grain", qty: 60, unitLoad: 4000, unitCopper: 5, ageQd: 0, shelfLifeQd: 100 }];
const services = [{ id: "daily", from: "A", to: "B", kind: "regular", capacity: 400000, travelQd: 4, firstQd: 4, intervalQd: 4, dispatchCopper: 10 }];
const newState = () => ({ enabled: true, version: 2, clockQd: 0, runs: [] });
const newHolding = (id = "h1") => ({ id, storage: { moneyCopper: 10000 }, special: {} });
const state = newState(), holding = newHolding();
const plan = planTransportChain({ cargo, services });
const order = bookTransportOrder({ state, holding, plan, services, id: "order1", direction: "inbound" });
assert.equal(holding.storage.moneyCopper, 9690, "goods paid and freight segregated immediately");
assert.equal(order.money.escrowCopper, 10);
let received = 0;
const dependencies = { receiveCargo: (_order, lots) => { received += lots.reduce((sum, lot) => sum + lot.qty, 0); } };
advanceTransportOrders({ state, holding, targetQd: 7, dependencies });
assert.equal(received, 0);
assert.equal(order.status, "travelling");
advanceTransportOrders({ state, holding, targetQd: 20, dependencies });
assert.equal(received, 60);
assert.equal(order.received[0].ageQd, 8, "age ends at actual receipt rather than period end");
advanceTransportOrders({ state, holding, targetQd: 20, dependencies });
assert.equal(received, 60, "period replay neither duplicates nor ages delivered cargo");
assert.equal(holding.storage.moneyCopper, 9690);

const cancelState = newState(), cancelledHolding = newHolding();
const cancelled = bookTransportOrder({ state: cancelState, holding: cancelledHolding, plan, services, id: "cancel", direction: "outbound" });
assert.equal(reservedResourceBatchQuantities(cancelledHolding, { id: "r1" }).get("b1"), 60);
cancelTransportOrder({ state: cancelState, holding: cancelledHolding, order: cancelled });
assert.equal(cancelledHolding.storage.moneyCopper, 10000);
assert.equal(reservedResourceBatchQuantities(cancelledHolding, { id: "r1" }).size, 0);
cancelTransportOrder({ state: cancelState, holding: cancelledHolding, order: cancelled });
assert.equal(cancelledHolding.storage.moneyCopper, 10000);

const shared = newState(), left = newHolding("left"), right = newHolding("right");
const risky = [{ ...services[0], riskBps: 10000 }];
const small = [{ ...cargo[0], qty: 30 }];
const leftPlan = planTransportChain({ cargo: small, services: risky });
const leftOrder = bookTransportOrder({ state: shared, holding: left, plan: leftPlan, services: risky, id: "left", direction: "inbound" });
const rightPlan = planTransportChain({ cargo: small, services: risky, runs: shared.runs });
const rightOrder = bookTransportOrder({ state: shared, holding: right, plan: rightPlan, services: risky, id: "right", direction: "inbound" });
assert.equal(shared.runs.length, 1);
advanceTransportOrders({ state: shared, holding: left, targetQd: 8, dependencies });
advanceTransportOrders({ state: shared, holding: right, targetQd: 8, dependencies });
assert.equal(leftOrder.status, "needsResolution");
assert.equal(rightOrder.status, "needsResolution");
resolveTransportIncident(shared, shared.runs[0].id, { outcome: "loss", lossBps: 10000 });
advanceTransportOrders({ state: shared, holding: left, targetQd: 8, dependencies });
advanceTransportOrders({ state: shared, holding: right, targetQd: 8, dependencies });
assert.equal(leftOrder.lostQty, 30);
assert.equal(rightOrder.lostQty, 30);
assert.equal(leftOrder.status, "lost");
assert.equal(rightOrder.status, "lost");

const delayedState = newState(), delayedHolding = newHolding();
const chain = [risky[0], { ...services[0], id: "connection", from: "B", to: "C", firstQd: 9 }];
const delayedPlan = planTransportChain({ cargo: small, services: chain });
const delayed = bookTransportOrder({ state: delayedState, holding: delayedHolding, plan: delayedPlan, services: chain, id: "delay", direction: "inbound" });
advanceTransportOrders({ state: delayedState, holding: delayedHolding, targetQd: 20, dependencies });
resolveTransportIncident(delayedState, delayed.stages[0].runs[0].id, { outcome: "delay", delayQd: 4 });
advanceTransportOrders({ state: delayedState, holding: delayedHolding, targetQd: 40, dependencies });
assert.equal(delayed.status, "delivered");
assert.ok(delayed.stages[1].runs[0].departureQd >= 24, "missed connection cannot be backdated");
assert.equal(delayed.money.spentCopper, delayedPlan.totalCopper, "carrier-caused rebooking preserves accepted fare");
console.log("transport-v2 runtime: escrow, protected cargo, cancellation, replay, age, shared physical incident and missed connection passed");

const fleet = newState(), fleetHolding = newHolding();
const charter = [{ ...services[0], id: "finite", kind: "charter", firstQd: 0, vehicles: 1, capacity: 40000, returnQd: 4, riskBps: 10000 }];
const ten = [{ ...cargo[0], qty: 10 }];
const earlier = bookTransportOrder({ state: fleet, holding: fleetHolding, plan: planTransportChain({ cargo: ten, services: charter }), services: charter, id: "earlier", direction: "inbound" });
const later = bookTransportOrder({ state: fleet, holding: fleetHolding, plan: planTransportChain({ cargo: ten, services: charter, runs: fleet.runs }), services: charter, id: "later", direction: "inbound" });
advanceTransportOrders({ state: fleet, holding: fleetHolding, targetQd: 12, dependencies });
assert.equal(later.stages[0].receipts.length, 0, "a charter cannot leave while its preceding voyage is unresolved");
resolveTransportIncident(fleet, earlier.stages[0].runs[0].id, { outcome: "delay", delayQd: 4 });
advanceTransportOrders({ state: fleet, holding: fleetHolding, targetQd: 24, dependencies });
assert.ok(later.stages[0].runs[0].departureQd >= 20, "actual empty return reserves the vehicle after a delay");
console.log("transport-v2 finite fleet: delay blocks the next order until actual return and rebooks its departure");
