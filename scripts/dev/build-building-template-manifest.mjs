const costByName = new Map();
for (const table of tables.filter((row) => row.h2 === "Норматив стоимости строительства" && row.headers[0] === "Шаблон")) {
  for (const row of table.rows) {
    const name = nameOf(row[0]);
    const materialCosts = [];
    const materialText = clean(row[3]);
    if (materialText && materialText !== "—") {
      for (const part of materialText.split(";").map((value) => value.trim()).filter(Boolean)) {
        const match = part.match(/^(.+?)\s+([\d\s]+)$/);
        if (!match) throw new Error(`${name}: cannot parse construction material ${part}`);
        const resourceId = resourceIdOf(match[1]);
        if (!resourceId) throw new Error(`${name}: unknown construction material ${match[1]}`);
        materialCosts.push({ id: `mat-${resourceId}`, name: match[1], resourceId, qty: Number(match[2].replace(/\s+/g, "")) });
      }
    }
    const moneyCopper = numberOf(row[4]);
    if (moneyCopper > 0) materialCosts.push({ id: "mat-money", name: "ММ", resourceId: "money", qty: moneyCopper });
    costByName.set(name, {
      buildTarget: numberOf(row[1]),
      buildDifficulty: numberOf(row[2]),
      materialCosts,
      sourceRawMaterials: [materialText && materialText !== "—" ? materialText : "", moneyCopper ? `${moneyCopper} ММ` : ""].filter(Boolean).join("; ") || "—"
    });
  }
}

