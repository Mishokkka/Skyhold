// Dev-only content extraction. Read a detached export; never open a live Foundry database.
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export function extractMagnifiqueCrew(input, additions) {
const actors = Array.isArray(input) && input.some((row) => row.key?.startsWith("!actors!"))
  ? input.filter((row) => /^!actors![^.]+$/.test(row.key)).map((row) => row.value)
  : (Array.isArray(input) ? input : input.actors ?? input.documents ?? []);
if (actors.length !== 27) throw new Error(`Expected 27 named Actors, found ${actors.length}.`);
const value = (field) => field && typeof field === "object" ? field.value ?? "" : field ?? "";
const plain = (field) => String(value(field)).replace(/<br\s*\/?\s*>|<\/p>/gi, "\n").replace(/<[^>]*>/g, "")
  .replace(/&nbsp;/g, " ").replace(/&hellip;/g, "…").replace(/&amp;/g, "&").replace(/&quot;/g, '"').replace(/&#39;/g, "'").trim();
const kinMap = { Human: ["Человек", ""], "Человек": ["Человек", ""], "Человек (Г)": ["Человек", "Гвирл"], "Гвирл": ["Человек", "Гвирл"], Elf: ["Эльф", ""], "Эльф": ["Эльф", ""], Dwarf: ["Дварф", ""], "Висверт": ["Дварф", "Висверт"], Goblin: ["Гоблин", ""], Ork: ["Орк", ""] };
const professions = { Fighter: "Воин", Apothecary: "Аптекарь", Mchm: "Моряк" };
const roles = { "Адмирал Элина Траззмар": "Командующая кораблём", "Капитан Рико Маллье": "Доверенный со-командующий", "Капитан Эдгар Тибо": "Доверенный со-командующий", "Лейтенант Сабрина Магнифик": "Управление кораблём", "Боцман Джитахар": "Боцман", "Мичман Джудит МакТрудде": "Кок", "Старшина Рутен Горт": "Наводчик", "Юнга Ангвар": "Юнга" };
const original = actors.map((actor) => {
  const bio = actor.system?.bio ?? {};
  const name = String(actor.name);
  const sourceActorId = actor._id;
  if (!/^[A-Za-z0-9]{16}$/.test(sourceActorId)) throw new Error(`Invalid Actor ID: ${name}`);
  const originalKin = plain(bio.kin);
  let [race, subrace] = kinMap[originalKin] ?? [originalKin, ""];
  let age = Number(value(bio.age));
  if (!Number.isInteger(age) || age <= 0) throw new Error(`Missing age: ${name}`);
  if (name === "Адмирал Элина Траззмар") age = 35;
  if (name === "Лейтенант Сабрина Магнифик") [race, subrace] = ["Полуэльф", ""];
  const attributes = Object.fromEntries(["strength", "agility", "wits", "empathy"].map((key) => {
    const score = actor.system?.attribute?.[key]?.max;
    if (!Number.isInteger(score) || score < 1 || score > 6) throw new Error(`Missing attribute ${key}: ${name}`);
    return [key, score];
  }));
  let notes = plain(bio.note);
  if (name === "Адмирал Элина Траззмар") notes = notes.replace("спустя 12 лет", "за более чем десятилетие");
  if (name === "Лейтенант Сабрина Магнифик") notes = notes.replace("первый корабельный ребенок", "первая воспитанница команды").replace("молодую эльфийку", "молодую полуэльфийку");
  const profession = plain(bio.profession);
  return {
    sourceCrewKey: `magnifique:actor:${sourceActorId}`, origin: "compendium", sourceActorId,
    name, rank: name.split(" ")[0], shipCrewRole: roles[name] ?? (name.startsWith("Старшина ") ? "Старшина палубной команды" : name.startsWith("Мичман ") ? "Мичман палубной команды" : "Палубная команда"),
    age, race, subrace, attributes, background: professions[profession] ?? profession,
    img: String(actor.img ?? ""),
    appearance: [plain(bio.face), plain(bio.body), plain(bio.clothing)].filter(Boolean).join("\n"),
    notes,
    sourceSkills: Object.fromEntries(Object.entries(actor.system?.skill ?? {}).map(([key, entry]) => [key, Number(entry?.value ?? 0)]).filter(([, score]) => Number.isFinite(score)))
  };
});
const roster = [...original, ...additions];
if (roster.length !== 36 || new Set(roster.map((row) => row.sourceCrewKey)).size !== 36) throw new Error("Invalid crew roster.");
return roster;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
const sourcePath = process.argv[2];
if (!sourcePath) throw new Error("Pass an Actor export JSON or detached decoded LevelDB JSON.");
const input = JSON.parse(await readFile(sourcePath, "utf8"));
const additions = JSON.parse(await readFile(new URL("../../docs/magnifique-crew-additions.json", import.meta.url), "utf8"));
const roster = extractMagnifiqueCrew(input, additions);
const output = fileURLToPath(new URL("../data/magnifique-crew.js", import.meta.url));
await writeFile(output, `// Public crew data only. Generated by scripts/dev/build-magnifique-crew.mjs.\n// Canon: year 882, Elina 35, Sabrina half-elf. Hidden Actor fields are never copied.\nconst rows = ${JSON.stringify(roster, null, 2)};\nfunction freeze(value) { if (value && typeof value === "object") { Object.values(value).forEach(freeze); Object.freeze(value); } return value; }\nexport const MAGNIFIQUE_CREW = freeze(rows);\nexport const MAGNIFIQUE_CREW_VERSION = 1;\n`);
console.log(`${roster.length} crew records written to ${path.basename(output)} (27 source, 9 additions).`);
}
