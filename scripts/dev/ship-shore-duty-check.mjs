import assert from "node:assert/strict";
import { isResidentPresent, isResidentInPopulation, isResidentRestingOnShip, hasResidentSettlementWork } from "../data/resident-presence.js";
import { embarkShipCrew, disembarkShipCrew } from "../engines/ships/crew.js";
import { ResidentDomain } from "../apps/domains/resident-domain.js";
import { createShipOperationExecutor } from "../apps/ship-operation-executor.js";
import { worldMarketFixture } from "./world-ship-market-characterization-check.mjs";

const fixture = worldMarketFixture();
let data = fixture.data;
const gm = { id: "gm", isGM: true }, player = { id: "player", isGM: false };
data.holdings[0].gm.playersCanEditResidents = true;
data.holdings[0].gm.playersCanManageShips = false;
data.holdings[0].visibility = "public";
const read = () => ({ holding: data.holdings[0], ship: data.holdings[0].special.ships.list[0], person: data.holdings[0].people.list[0] });
let { holding, ship, person } = read();
assert.equal(isResidentPresent(person), true);
assert.equal(isResidentRestingOnShip(person, holding), true, "crew membership suffices before the first voyage marker exists");
assert.equal(isResidentInPopulation(person, holding), false);
assert.deepEqual(ResidentDomain._preparePeopleTabs.call({ activePeopleTab: "ship-crew" }, holding).map((row) => [row.id, row.count, row.active]), [["living", 0, false], ["ship-crew", 1, true]]);
assert.equal(ResidentDomain._calculatePersonMorale(person, holding).total, 0);
person.home = "house";
holding.buildings.list = [{ id: "house", name: "Дом", functions: { housing: true }, housing: { capacity: 1 } }];
const housingMethods = { ...ResidentDomain };
assert.equal(housingMethods._residentHousingIndex(holding).occupantsByBuildingKey.size, 0, "a stale home must not occupy housing while aboard");
assert.equal(housingMethods._housingOccupants(holding, holding.buildings.list[0]).length, 0);
assert.equal(hasResidentSettlementWork({ id: "test", workAllocationMode: "explicit", workAllocations: [{ normalQd: 2 }] }, holding), true);

const skipToken = Symbol("skip");
let commits = 0;
const execute = createShipOperationExecutor({
  getUser: (id) => id === "gm" ? gm : player,
  skip: (value) => ({ [skipToken]: true, value }),
  updateHolding: async (_id, updater) => {
    const draft = structuredClone(data);
    const result = await updater(draft.holdings[0], draft);
    if (result?.[skipToken]) return result.value;
    draft.meta.revision += 1; data = draft; commits += 1; return result;
  }
});
const operation = { type: "shore-duty", operationId: "shore-test", expectedRevision: 1, holdingId: holding.id, shipId: ship.id, residentId: person.id };
const original = JSON.stringify(data);
await assert.rejects(execute({ ...operation, residentId: "unknown" }, { userId: "gm" }), /составе/);
assert.equal(JSON.stringify(data), original);
data.holdings[0].gm.playersCanEditResidents = false;
await assert.rejects(execute(operation, { userId: "player", remote: true }), /Нет права/);
data.holdings[0].gm.playersCanEditResidents = true;
data.holdings[0].visibility = "gm";
await assert.rejects(execute(operation, { userId: "player", remote: true }), /Нет права/);
data.holdings[0].visibility = "public";
assert.equal((await execute(operation, { userId: "player", remote: true })).shoreDuty, true);
assert.equal((await execute(operation, { userId: "player", remote: true })).replay, true);
assert.equal(commits, 1, "retry never enrolls or bills twice");
({ holding, ship, person } = read());
assert.equal(isResidentInPopulation(person, holding), true);
assert.equal(isResidentRestingOnShip(person, holding), false);
assert.equal(housingMethods._housingOccupants(holding, holding.buildings.list[0]).length, 1);
const returnOperation = { type: "return-to-ship", operationId: "return-test", expectedRevision: 2, holdingId: holding.id, shipId: ship.id, residentId: person.id };
person.home = "house";
person.workAssignment = "house";
person.workAllocationMode = "explicit";
person.workAllocations = [{ buildingId: "house", normalQd: 2, overtimeQd: 1 }];
person.staffAppointment = { version: 1, buildingId: "house", primaryFunctionId: "housing", reserveFunctionId: "",
  wageDailyCopper: 12, overtimeQd: 0, volunteer: false, volunteerReason: "" };
holding.buildings.list[0].assignedWorkerIds = [person.id];
holding.buildings.list[0].workerAdmissionOverrideIds = [person.id];
holding.constructionCrews = [{
  id: "crew", memberIds: [person.id], distributedIds: [person.id], leaderId: person.id, distributedLeaderId: person.id
}];
holding.constructionCrewIds = [person.id];
holding.gm.defense = { commanderId: person.id, squads: [{ memberIds: [person.id], sergeantId: person.id }] };
const crewBeforeReturn = [...ship.crewResidentIds];
holding.gm.playersCanEditResidents = false;
await assert.rejects(execute(returnOperation, { userId: "player", remote: true }), /Нет права/);
holding.gm.playersCanEditResidents = true;
ship.location.kind = "market";
await assert.rejects(execute(returnOperation, { userId: "gm" }), /только когда корабль дома/);
ship.location.kind = "home";
const returnedToShip = await execute(returnOperation, { userId: "player", remote: true });
assert.equal(returnedToShip.shoreDuty, false);
assert.equal(returnedToShip.clearedAssignments, 14, "The staff contract is one additional assignment cleared by this fixture");
assert.equal((await execute(returnOperation, { userId: "player", remote: true })).replay, true);
assert.equal(commits, 2, "return retry never clears or bills twice");
({ holding, ship, person } = read());
assert.deepEqual(ship.crewResidentIds, crewBeforeReturn, "returning one resident does not change the crew roster");
assert.equal(person.shipAssignment.shoreDuty, undefined);
assert.equal(person.shipAssignment.away, false);
assert.equal(person.home, "");
assert.equal(person.workAssignment, "");
assert.equal(person.staffAppointment, undefined, "The authorized return-to-ship operation must release a permanent civilian contract");
assert.equal(person.workAllocationMode, "legacy");
assert.deepEqual(person.workAllocations, []);
assert.deepEqual(holding.buildings.list[0].assignedWorkerIds, [""]);
assert.deepEqual(holding.buildings.list[0].workerAdmissionOverrideIds, []);
assert.deepEqual(holding.constructionCrews[0].memberIds, []);
assert.deepEqual(holding.constructionCrews[0].distributedIds, []);
assert.equal(holding.constructionCrews[0].leaderId, "");
assert.equal(holding.constructionCrews[0].distributedLeaderId, "");
assert.deepEqual(holding.constructionCrewIds, []);
assert.equal(holding.gm.defense.commanderId, "");
assert.deepEqual(holding.gm.defense.squads[0].memberIds, [""]);
assert.equal(holding.gm.defense.squads[0].sergeantId, "");
assert.equal(isResidentRestingOnShip(person, holding), true);

person.shipAssignment.shoreDuty = true;
person.home = "house";
holding.buildings.list[0].assignedWorkerIds = [person.id];
holding.constructionCrews = [{ id: "crew", memberIds: [person.id], leaderId: person.id }];
holding.gm.defense = { commanderId: person.id, squads: [{ memberIds: [person.id], sergeantId: person.id }] };
person.workAssignment = "";
assert.equal(isResidentInPopulation(person, holding), true, "shore duty survives a vacancy until departure");
embarkShipCrew(holding, ship, 4);
assert.equal(person.home, "");
assert.equal(person.shipAssignment.shoreDuty, undefined);
assert.equal(isResidentInPopulation(person, holding), false);
assert.deepEqual(holding.buildings.list[0].assignedWorkerIds, [""]);
assert.deepEqual(holding.constructionCrews[0].memberIds, []);
assert.equal(holding.gm.defense.commanderId, "");
assert.deepEqual(holding.gm.defense.squads[0].memberIds, [""]);
await assert.rejects(execute({ ...operation, operationId: "shore-while-away", expectedRevision: 3 }, { userId: "gm" }), /составе/);
await assert.rejects(execute({ type: "crew", operationId: "remove-away-crew", holdingId: holding.id, shipId: ship.id, crewResidentIds: [], expectedRevision: 3 }, { userId: "gm" }), /вне поселения/);
disembarkShipCrew(holding, ship, 8);
assert.equal(isResidentRestingOnShip(person, holding), true);
assert.equal(person.home, "");
assert.equal(person.workAssignment, "");
const noMembership = structuredClone(holding);
noMembership.special.ships.list[0].crewResidentIds = [];
assert.equal(isResidentInPopulation(person, noMembership), true, "a historic marker is not current membership");
console.log("FBL Skyhold ship shore duty check passed.");
